-- Per-user archive of generated AI analyses.
--
-- The application writes through the user-scoped Supabase client, so Row Level
-- Security is the last line of defence: even a bug in a query cannot expose
-- another account's history. Account deletion cascades from auth.users.

create table if not exists public.analyses (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  cache_key text not null,
  corpus_id text not null,
  book_id text not null,
  chapter integer not null check (chapter > 0),
  verse_from integer not null check (verse_from > 0),
  verse_to integer not null check (verse_to >= verse_from),
  mode text not null check (mode in ('resumen', 'explicacion', 'gramatica')),
  reference text not null,
  text text not null,
  model text not null,
  prompt_version integer not null default 1,
  usage jsonb,
  created_at timestamptz not null default now(),
  constraint analyses_user_cache_key_key unique (user_id, cache_key)
);

create index if not exists analyses_user_created_idx
  on public.analyses (user_id, created_at desc);

alter table public.analyses enable row level security;

revoke all on public.analyses from anon;
grant select, insert, update, delete on public.analyses to authenticated;

drop policy if exists "analyses_select_own" on public.analyses;
create policy "analyses_select_own"
  on public.analyses
  for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "analyses_insert_own" on public.analyses;
create policy "analyses_insert_own"
  on public.analyses
  for insert
  to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "analyses_update_own" on public.analyses;
create policy "analyses_update_own"
  on public.analyses
  for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "analyses_delete_own" on public.analyses;
create policy "analyses_delete_own"
  on public.analyses
  for delete
  to authenticated
  using (auth.uid() = user_id);

comment on table public.analyses is
  'AI analyses generated by authenticated users. One row per user and cache key.';
