export function featureValueLabel(
  feature: Pick<FeatureValue, "enumName" | "value" | "kind">,
): string {
  const labels = feature.enumName ? VALUE_LABELS[feature.enumName] : undefined;
  if (!labels) {
    return feature.value;
  }
  if (feature.kind === "multi-enum") {
    return feature.value
      .split(",")
      .map((item) => labels[item.trim()] ?? item.trim())
      .join(", ");
  }
  return labels[feature.value] ?? feature.value;
}
